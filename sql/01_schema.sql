-- =============================================================================
-- 01_schema.sql — Dallas 311 analytics database
--
-- Three layers:
--   staging    raw CSV rows, every column as text, exactly as the portal delivers them
--   core       typed, de-duplicated, normalized tables (3NF) with keys and constraints
--   analytics  read-only views and materialized views that analysts and dashboards query
--
-- Re-runnable: drops and rebuilds all three schemas.
-- =============================================================================

DROP SCHEMA IF EXISTS analytics CASCADE;
DROP SCHEMA IF EXISTS core CASCADE;
DROP SCHEMA IF EXISTS staging CASCADE;

CREATE SCHEMA staging;
CREATE SCHEMA core;
CREATE SCHEMA analytics;

COMMENT ON SCHEMA staging   IS 'Raw 311 rows as downloaded (text). Loaded with COPY.';
COMMENT ON SCHEMA core      IS 'Typed, de-duplicated, normalized 311 data with constraints.';
COMMENT ON SCHEMA analytics IS 'Views and materialized views for analysis and dashboards.';

-- -----------------------------------------------------------------------------
-- staging
-- -----------------------------------------------------------------------------
CREATE TABLE staging.sr_raw (
    service_request_number           text,
    address                          text,
    city_council_district            text,
    department                       text,
    service_request_type             text,
    ert_estimated_response_time      text,
    overall_service_request_due_date text,
    status                           text,
    created_date                     text,
    update_date                      text,
    closed_date                      text,
    outcome                          text,
    priority                         text,
    method_received_description      text,
    lat_location                     text,
    source_file                      text        -- which extract the row came from
);

-- Rows that fail a validation rule land here with the reason, instead of being silently dropped.
CREATE TABLE staging.sr_rejects (
    LIKE staging.sr_raw,
    reject_reason text NOT NULL
);

-- -----------------------------------------------------------------------------
-- core (reference + dimension tables)
-- -----------------------------------------------------------------------------
-- When the extract was pulled (America/Chicago local time). Used to age the open backlog.
CREATE TABLE core.extract_info (
    pulled_at_utc   timestamptz NOT NULL,
    pulled_at_local timestamp   NOT NULL,
    source_url      text        NOT NULL
);

CREATE TABLE core.department (
    department_id    smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    department_name  text NOT NULL UNIQUE,   -- canonical name
    department_short text NOT NULL UNIQUE    -- label for charts
);

-- The portal spells some departments two ways (e.g. "Sanitation" and "Sanitation Services").
-- Every raw spelling maps to exactly one canonical department here.
CREATE TABLE core.department_alias (
    raw_name      text     PRIMARY KEY,
    department_id smallint NOT NULL REFERENCES core.department (department_id)
);

CREATE TABLE core.request_type (
    request_type_id   integer  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    request_type_name text     NOT NULL,
    department_id     smallint NOT NULL REFERENCES core.department (department_id),
    UNIQUE (request_type_name, department_id)
);

CREATE TABLE core.channel (
    channel_id   smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel_name text NOT NULL UNIQUE,
    -- 'External' = submitted from outside city operations (residents, businesses, partner systems via phone, app, web, email, API);
    -- 'City'     = generated by city staff or systems (proactive inspections, internal, camera detection)
    initiated_by text NOT NULL CHECK (initiated_by IN ('External', 'City', 'Unknown'))
);

-- Every status the portal uses, classified once so every query agrees on what "open" means.
CREATE TABLE core.status (
    status_name  text    PRIMARY KEY,
    is_open      boolean NOT NULL,
    is_duplicate boolean NOT NULL,
    -- closed by the responsible department (not a duplicate, a transfer to another agency, or a cancel)
    is_resolved  boolean NOT NULL,
    CHECK (NOT (is_open AND is_resolved))
);

-- -----------------------------------------------------------------------------
-- core (fact table): one row per service request
-- -----------------------------------------------------------------------------
CREATE TABLE core.service_request (
    sr_number        text      PRIMARY KEY,
    request_type_id  integer   NOT NULL REFERENCES core.request_type (request_type_id),
    channel_id       smallint  REFERENCES core.channel (channel_id),
    status_name      text      NOT NULL REFERENCES core.status (status_name),
    council_district smallint  CHECK (council_district BETWEEN 1 AND 14),
    priority         text,
    outcome          text,
    ert_text         text,                 -- published estimated response time, e.g. "7 Business Days"
    address          text,
    zip_code         char(5)   CHECK (zip_code ~ '^[0-9]{5}$'),
    latitude         numeric(9, 6) CHECK (latitude  BETWEEN 32.4 AND 33.2),
    longitude        numeric(9, 6) CHECK (longitude BETWEEN -97.2 AND -96.3),
    created_at       timestamp NOT NULL,   -- local Dallas time, as published
    due_at           timestamp,            -- "overall service request due date" (the service target)
    closed_at        timestamp,
    updated_at       timestamp,
    -- City of Dallas fiscal year runs Oct 1 - Sep 30 (FY2026 = Oct 2025 - Sep 2026)
    fiscal_year      smallint GENERATED ALWAYS AS
                         ((EXTRACT(YEAR FROM created_at + INTERVAL '3 months'))::smallint) STORED,
    days_to_close    numeric GENERATED ALWAYS AS
                         (EXTRACT(EPOCH FROM (closed_at - created_at)) / 86400.0) STORED,
    closed_on_time   boolean GENERATED ALWAYS AS
                         (CASE WHEN closed_at IS NULL OR due_at IS NULL THEN NULL
                               ELSE closed_at <= due_at END) STORED,
    CONSTRAINT closed_not_before_created CHECK (closed_at IS NULL OR closed_at >= created_at)
);

COMMENT ON TABLE  core.service_request IS 'One row per Dallas 311 service request (deduplicated on sr_number).';
COMMENT ON COLUMN core.service_request.due_at IS 'Overall service request due date published by the city: the service-level target.';
COMMENT ON COLUMN core.service_request.closed_on_time IS 'TRUE when closed at or before due_at; NULL while open or when no due date exists.';
